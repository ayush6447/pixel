/**
 * The spider mark, traced off assets/logo.png into a 34 x 43 pixel map and
 * drawn as rects rather than shipped as a bitmap. That way it inherits
 * currentColor, stays crisp at any size, and costs about a kilobyte.
 *
 * The same map generates app/icon.svg — regenerate both together if the
 * source art ever changes.
 */
