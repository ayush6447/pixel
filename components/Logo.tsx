const COLS = 34;
const ROWS = SPIDER.length;
const RUNS = toRuns(SPIDER);

export default function Logo({ className }: { className?: string }) {
  return (
    <svg
      className={className}
      viewBox={`0 0 ${COLS} ${ROWS}`}
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
    >
      {RUNS.map((r) => (
        <rect key={`${r.y}-${r.x}`} x={r.x} y={r.y} width={r.w} height={1} />
      ))}
    </svg>
  );
}
